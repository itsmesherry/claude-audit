import fs from 'fs';
import type { AuditReport, Severity } from '../core/types';

const SEVERITY_ORDER: Severity[] = ['critical', 'high', 'medium', 'low', 'info'];

function title(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function generateMarkdownReport(report: AuditReport, outputPath: string): void {
  const { project, categories, allFindings } = report;
  const lines: string[] = [];

  const mode = report.agentic ? 'agentic audit' : report.aiPowered ? 'one-shot AI audit' : 'static analysis only';
  const stack = [...Object.keys(project.languages), ...project.frameworks].join(', ');

  lines.push(`# Audit report: ${project.name}`);
  lines.push('');
  lines.push(`**Score ${report.overallScore}/100 (${report.overallGrade})** · ${report.criticalCount} critical, ${report.highCount} high, ${report.mediumCount} medium, ${report.lowCount} low`);
  lines.push('');
  lines.push(`${project.totalFiles.toLocaleString()} files, ${project.totalLines.toLocaleString()} lines${stack ? ' · ' + stack : ''} · ${mode} · ${new Date(report.timestamp).toISOString().slice(0, 10)}`);
  lines.push('');

  for (const warning of report.warnings ?? []) {
    lines.push(`> **Warning:** ${warning}`);
    lines.push('');
  }

  lines.push('| Category | Score | Grade | Findings |');
  lines.push('|----------|------:|:-----:|---------:|');
  for (const cat of categories) {
    lines.push(`| ${title(cat.category)} | ${cat.score} | ${cat.grade} | ${cat.findings.length} |`);
  }
  lines.push('');

  const summaries = categories.filter(c => c.summary);
  if (summaries.length > 0) {
    lines.push('## Summary');
    lines.push('');
    for (const cat of summaries) {
      lines.push(`- **${title(cat.category)}:** ${cat.summary}`);
    }
    lines.push('');
  }

  if (allFindings.length > 0) {
    lines.push('## Findings');
    lines.push('');
  }
  for (const severity of SEVERITY_ORDER) {
    for (const f of allFindings.filter(x => x.severity === severity)) {
      const location = f.file ? ` · \`${f.line ? `${f.file}:${f.line}` : f.file}\`` : '';
      lines.push(`### ${title(severity)}: ${f.title}`);
      lines.push('');
      lines.push(`${title(f.category)}${location}`);
      lines.push('');
      // Static secret findings carry a description that only repeats the title
      if (f.description && f.description !== `Potential ${f.title} found in source code.`) {
        lines.push(f.description);
        lines.push('');
      }
      if (f.snippet) {
        lines.push('```');
        lines.push(f.snippet);
        lines.push('```');
        lines.push('');
      }
      if (f.fix) {
        lines.push(`**Fix:** ${f.fix}`);
        lines.push('');
      }
    }
  }

  if (report.agentTrace) {
    const s = report.agentTrace.summary;
    lines.push('## Agent run');
    lines.push('');
    lines.push(
      `\`${report.agentTrace.model}\` · ${s.turns}/${report.agentTrace.maxTurns} turns · ${s.toolCalls} tool calls · ` +
      `${s.inputTokens.toLocaleString()} in / ${s.outputTokens.toLocaleString()} out tokens · stopped: ${s.stopReason}` +
      (s.stopDetail ? ` (${s.stopDetail})` : ''),
    );
    lines.push('');
  }

  lines.push('---');
  lines.push('');
  lines.push(`Generated by [claude-audit](https://github.com/itsmesherry/claude-audit) ${report.version}`);

  fs.writeFileSync(outputPath, lines.join('\n') + '\n', 'utf-8');
}
